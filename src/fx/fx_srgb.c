uint8_t fxl_encode(double v)
{
    int lo = 0, hi = 255;          /* answer in [lo, hi] */
    if (!(v > 0.0)) return 0;      /* also NaN */
    if (v >= 1.0) return 255;
    while (lo < hi) {
        int mid = (lo + hi + 1) >> 1;
        if (fxl_mid_tab[mid - 1] <= v) lo = mid;
        else hi = mid - 1;
    }
    return (uint8_t)lo;
}

fx_pxf fxl_premul(fx_px p)
{
    fx_pxf q;
    float a = (float)p.a;
    q.b = (float)fxl_lin_tab[p.b] * a;
    q.g = (float)fxl_lin_tab[p.g] * a;
    q.r = (float)fxl_lin_tab[p.r] * a;
    q.a = a;
    return q;
}

fx_px fxl_unpremul(fx_pxf q)
{
    fx_px p;
    float a = q.a;
    int32_t a8;
    if (!(a > 0.0f)) return fx_px_make(0, 0, 0, 0);
    a8 = (int32_t)floorf(a + 0.5f);
    if (a8 <= 0) return fx_px_make(0, 0, 0, 0);
    if (a8 > 255) a8 = 255;
    p.b = fxl_encode((double)q.b / (double)a);
    p.g = fxl_encode((double)q.g / (double)a);
    p.r = fxl_encode((double)q.r / (double)a);
    p.a = (uint8_t)a8;
    return p;
}
